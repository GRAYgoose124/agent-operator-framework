# ---------------------------------------------------------------- concepts (tier 0, deterministic)

def test_candidate_phrases_skip_generic_edges_and_fold_plurals():
    keys = candidate_phrases("These results suggest that place cells and grid cells support navigation.")
    assert "place cell" in keys and "grid cell" in keys
    assert not any(k.startswith(("result", "suggest")) for k in keys)
    assert "support" not in keys and "cell" not in keys  # verbs and generic nouns are never concepts alone


def test_acronyms_merge_into_their_expansion_when_defined_twice():
    texts = [
        "The thalamic reticular nucleus (TRN) gates sensory input.",
        "Neurons of the thalamic reticular nucleus (TRN) are GABAergic.",
        "The medial dorsolateral (MD) region appears once only.",
    ]
    defs = acronym_definitions(texts)
    assert defs["TRN"] == "thalamic reticular nucleu" or defs["TRN"].startswith("thalamic reticular")
    assert "MD" not in defs  # a single definition could be a coincidence of initials


def test_extract_concepts_on_the_fixture_sentences():
    items = [(f"{k}-{i}", s) for k, (_, ss) in PAPERS.items() for i, s in enumerate(ss)]
    concepts, assigned = extract_concepts(items, min_df=2, max_share=0.5)
    labels = {c.label.lower() for c in concepts}
    assert {"grid cells", "place cells", "sleep spindles", "sharp-wave ripples"} <= labels | {"sharp wave ripples"}
    assert any(c.key.lower() == "trn" or "reticular" in c.key for c in concepts)
    assert all(len(v) <= 3 for v in assigned.values())
    related = related_concepts(concepts, assigned, min_pair=1)
    assert related  # co-mentioned concepts are related


