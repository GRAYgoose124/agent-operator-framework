async def test_export_removes_stale_files_and_keeps_user_graph_settings(vault):
    store, _, embed, tmp = vault
    await build_graph(store, None, embed, GraphOptions(concept_min_df=2, concept_max_share=0.5, hub_min_size=2,
                                                       max_hub_size=6))
    out = tmp / "export"
    (out / "claims").mkdir(parents=True)
    (out / "claims" / "stale note.md").write_text("---\nid: gone\n---\n", encoding="utf-8")
    (out / ".obsidian").mkdir()
    (out / ".obsidian" / "graph.json").write_text('{"mine": true}', encoding="utf-8")
    counts = await export_vault(store, out)
    assert not (out / "claims" / "stale note.md").exists()
    assert json.loads((out / ".obsidian" / "graph.json").read_text(encoding="utf-8")) == {"mine": True}
    assert counts["claims"] == 18 and counts["concepts"] >= 4 and counts["sources"] == 6
    concept_file = next((out / "concepts").iterdir()).read_text(encoding="utf-8")
    assert "Concept: **" in concept_file and "[[" in concept_file
    claim_file = next((out / "claims").iterdir()).read_text(encoding="utf-8")
    assert "**Source:**" in claim_file and "**Concepts:**" in claim_file


