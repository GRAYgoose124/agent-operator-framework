async def test_retrieval_spreads_through_concepts_and_caps_each_work(vault):
    store, _, embed, _ = vault
    await build_graph(store, None, embed, GraphOptions(concept_min_df=2, concept_max_share=0.5, hub_min_size=2,
                                                       max_hub_size=6))
    graph = await VaultGraph(store, embed).load()
    got = await graph.retrieve(["How do sleep spindles relate to the thalamic reticular nucleus?"], k=6, per_work=2)
    works = [e.source_url for e in got]
    assert got and max(works.count(w) for w in works) <= 2
    assert any("spindle" in e.text.lower() for e in got[:3])
    assert got[0].source_label.endswith(")") and got[0].concepts

    first = {e.note_id for e in got}
    again = await graph.retrieve(["sleep spindles thalamic reticular nucleus"], k=6, per_work=2, used=first,
                                 used_penalty=1.0)
    assert not ({e.note_id for e in again} & first) or len(again) < 6  # used claims are pushed down
    budgeted = await graph.retrieve(["grid cells"], k=20, token_budget=60)
    assert 1 <= len(budgeted) <= 3
    vmap = await graph.vault_map(["grid cells and place cells"], hubs=3, concepts=5)
    assert {m.kind for m in vmap} == {"hub", "concept"}


async def test_embedding_cache_hits_on_second_call(tmp_path):
    calls = []

    async def fake_embed(texts):  # counts calls; vectors are deterministic
        calls.append(list(texts))
        return [[float(len(t)), 1.0] for t in texts]

    cache = EmbeddingCache(tmp_path / "e.db", "m")
    embed = cache.wrap(fake_embed)
    assert await embed(["a", "bb"]) == [[1.0, 1.0], [2.0, 1.0]]
    assert await embed(["bb", "ccc"]) == [[2.0, 1.0], [3.0, 1.0]]
    assert calls == [["a", "bb"], ["ccc"]] and cache.hits == 1
    cache.close()


