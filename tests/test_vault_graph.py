needs_small = pytest.mark.skipif(
    not os.path.exists(resolve_role_path(CONFIG, "small")), reason="local small role model not available"
)


@needs_small
async def test_report_writer_end_to_end_with_small_model(vault):
    from aof.specialists.backends import RoleBackends
    from aof.specialists.role_provider import RoleProvider

    store, registry, embed, tmp = vault
    await build_graph(store, None, embed, GraphOptions(concept_min_df=2, concept_max_share=0.5, hub_min_size=2,
                                                       max_hub_size=6))
    backends = RoleBackends(CONFIG)
    judge_provider = RoleProvider("small", CONFIG, backends.get)

    async def generate(system, user, max_tokens):
        from aof.inference.parsing import parse_response

        b = await backends.get("small")
        r = await b.complete([{"role": "system", "content": system}, {"role": "user", "content": user}],
                             temperature=0.3, max_tokens=max_tokens)
        return parse_response(r.text).text

    async def judge(statement, evidence):
        r = await judge_provider.judge(statement, evidence)
        return r.value["verdict"] if r else "needs_lookup"

    steered = []

    async def control():
        if not steered:
            steered.append(1)
            return ["Mention species where the evidence names them."]
        return []

    try:
        graph = await VaultGraph(store, embed).load()
        writer = ReportWriter(
            store, graph, generate, judge=judge, confirm=None, workspace_root=tmp, control=control,
            options=ReportOptions(sections=3, ctx_tokens=CONFIG.role_context.get("small", 4096), section_words=150,
                                  section_out_tokens=500, min_evidence=2),
            writer_name="small",
        )
        state = await writer.run("How do sleep, the TRN and hippocampal ripples relate?")
    finally:
        await backends.close()

    assert state.stage == "done" and len(state.drafts) >= 3 and all(d.text for d in state.drafts)
    assert "Mention species where the evidence names them." in state.guidance  # steering picked up mid-run
    md = (tmp / "reports" / "how-do-sleep-the-trn-and-hippocampal-ripples-relate.md").read_text(encoding="utf-8")
    import re

    assert md.startswith("# ") and "## References" in md and re.search(r"\[1[\],]", md)
    assert "\n1. “" in md.split("## References", 1)[1]  # the first reference quotes its claim
    from aof.refine.report import report_note_id

    note = await store.get_note(report_note_id(state.topic))
    assert note is not None and note.kind == "report" and note.links and all(l.startswith("c-") for l in note.links)
    # resuming a finished report does not rewrite it
    again = await ReportWriter(store, graph, generate, workspace_root=tmp, options=writer.opt).run(state.topic)
    assert [d.text for d in again.drafts] == [d.text for d in state.drafts]
