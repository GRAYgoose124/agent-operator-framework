async def test_build_graph_layers_and_idempotence(vault):
    store, registry, embed, _ = vault
    opts = GraphOptions(concept_min_df=2, concept_max_share=0.5, hub_min_size=2, max_hub_size=6, link_min_sim=0.4)
    report = await build_graph(store, None, embed, opts)
    assert report.claims == 18 and report.sources == 6 and report.concepts >= 4 and report.hubs >= 2

    claim = await store.get_note("c-trn-b-0")
    kinds = {}
    for link in claim.links:
        kinds.setdefault((await store.get_note(link)).kind, []).append(link)
    assert kinds.get("source") and kinds.get("concept") and kinds.get("hub")
    for other in kinds.get("claim", []):  # claim-claim links join different papers only (same paper = source note)
        assert not other.startswith("c-trn-b-")

    src = await store.get_note(kinds["source"][0])
    assert src.kind == "source" and "Sleep spindles and the TRN" in src.title and len(src.links) == 3
    concept = await store.get_note(kinds["concept"][0])
    assert concept.kind == "concept" and "claim" not in concept.tags and "c-trn-b-0" in concept.links

    again = await build_graph(store, None, embed, opts)
    assert again.claims_changed == 0  # nothing derived changed: idempotent

    shape = graph_shape([*(await store.get_notes_by_tags(["claim", "hub", "concept", "source"], limit=1000))])
    assert shape["isolated_nodes"] == 0 and shape["duplicate_hub_titles"] == 0
    assert shape["claims_with_concept"] > 0.8


def test_mutual_knn_skips_same_work_and_near_duplicates():
    notes = [ZettelNote(id=x, title=x, content=x) for x in "abcd"]
    vecs = {"a": [1.0, 0.0, 0.0], "b": [0.9, 0.3, 0.0], "c": [0.8, 0.5, 0.1], "d": [1.0, 0.0001, 0.0]}
    works = {"a": {"w1"}, "b": {"w1"}, "c": {"w2"}, "d": {"w3"}}
    edges = mutual_knn(notes, vecs, k=2, min_sim=0.5, max_sim=0.99, same_work=works)
    assert "b" not in edges["a"]  # same paper
    assert "d" not in edges["a"]  # cosine ~1.0: a duplicate, not a relation
    assert all(x in edges[y] for x, ys in edges.items() for y in ys)  # mutual


