def test_outline_drops_frame_sections_and_prose_is_cleaned():
    from aof.refine.report import clean_prose

    titles = ["Introduction", "Anatomy", "Spindles", "Attention", "Synthesis of TRN functions", "Conclusions"]
    text = "".join(f"SECTION: {t}\nFOCUS: f\n" for t in titles)
    _, plans = parse_outline(text, 9)
