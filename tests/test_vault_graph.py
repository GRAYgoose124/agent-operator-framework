# ---------------------------------------------------------------- hubs: balanced splits

def test_kmeans_split_is_balanced_and_hub_tree_caps_hub_size():
    rng = np.random.default_rng(0)
    centre = rng.normal(size=16)
    notes, vectors = [], {}
    for i in range(300):  # one dense blob: threshold clustering alone cannot split it
        nid = f"n{i:03d}"
        notes.append(ZettelNote(id=nid, title=nid, content=f"claim {i}", kind="claim"))
        vectors[nid] = (centre + 0.35 * rng.normal(size=16)).tolist()
    parts = kmeans_split(notes, vectors, 4)
    assert len(parts) == 4 and min(len(p) for p in parts) >= 30
    tree = hub_tree(notes, vectors, threshold=0.5, min_size=3, max_size=40)

    def leaves(nodes):
        for n in nodes:
            yield from (leaves(n.children) if n.children else [n])

    assert max(len(leaf.members) for leaf in leaves(tree)) <= 60


